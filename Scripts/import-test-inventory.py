#!/usr/bin/env python3
"""Import the unchanged pinned ccstate Vitest JSON report (no test code execution)."""
import json
from pathlib import Path
import sys

report = json.loads(Path(sys.argv[1]).read_text())
assert report['success'] and report['numFailedTests'] == 0
root = Path(__file__).resolve().parent.parent
tests = []
for suite in report['testResults']:
    path = 'packages/ccstate/src/' + suite['name'].split('/src/', 1)[1]
    group = Path(path).name.removesuffix('.test.ts')
    for index, case in enumerate(suite['assertionResults'], 1):
        identifier = f'{group}.{index:02}'
        kind = 'behavioral-port'
        if identifier in ('ccstate.03', 'watch-listener-prototype.05'):
            kind = 'compile-time-enforcement'
        elif group == 'promise':
            kind = 'native-task-adaptation'
        elif group == 'tree-shaking':
            kind = 'javascript-toolchain-only'
        tests.append(dict(id=identifier, file=path, name=case['fullName'], kind=kind))
tests.sort(key=lambda x: x['id'])
manifest = dict(repository='https://github.com/e7h4n/ccstate',
                commit='86f95f2841c15474f08fcfc8e040c078dd2ab093', version='6.1.0', tests=tests)
(root / 'Compatibility/upstream-tests.json').write_text(json.dumps(manifest, indent=2) + '\n')
lines = ['// Generated by Scripts/import-test-inventory.py from the pinned upstream test report.',
         'internal let upstreamCases: [UpstreamCase] = [']
for t in tests:
    if t['kind'] == 'javascript-toolchain-only':
        continue
    lines.append(f'    UpstreamCase(id: {json.dumps(t["id"])}, name: {json.dumps(t["name"])}, file: {json.dumps(t["file"])}),')
lines.append(']')
(root / 'Tests/CCStateTests/UpstreamInventory.swift').write_text('\n'.join(lines) + '\n')
print(f'Imported {len(tests)} passing upstream cases')
